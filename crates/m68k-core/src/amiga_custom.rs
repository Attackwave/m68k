/// Bit fields of a register, empty when it holds a plain value (pointer,
/// modulo, data).
pub fn fields(register: &Register) -> &'static [Field] {
    let name = register.name;
    let family = |prefix: &str, suffix: &str| {
        name.strip_prefix(prefix)
            .and_then(|rest| rest.strip_suffix(suffix))
            .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
    };
    match name {
        "DMACON" | "DMACONR" => DMACON,
        "INTENA" | "INTENAR" | "INTREQ" | "INTREQR" => INTENA,
        "ADKCON" | "ADKCONR" => ADKCON,
        "BPLCON0" => BPLCON0,
        "BPLCON1" => BPLCON1,
        "BPLCON2" => BPLCON2,
        "BPLCON3" => BPLCON3,
        "BPLCON4" => BPLCON4,
        "BLTCON0" => BLTCON0,
        "BLTCON1" => BLTCON1,
        "BLTSIZE" => BLTSIZE,
        "COPCON" => COPCON,
        "BEAMCON0" => BEAMCON0,
        "FMODE" => FMODE,
        "CLXCON" => CLXCON,
        "CLXCON2" => CLXCON2,
        "DSKLEN" => DSKLEN,
        "SERPER" => SERPER,
        "POTGO" => POTGO,
        "DIWSTRT" | "DIWSTOP" => DIW,
        _ if family("COLOR", "") => COLOR,
        _ if family("AUD", "VOL") => AUDVOL,
        _ if family("SPR", "POS") => SPRPOS,
        _ if family("SPR", "CTL") => SPRCTL,
        _ => &[],
    }
}

/// One field of a decoded value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Decoded {
    pub field: Field,
    pub value: u16,
}

/// The fields a written or read value sets. Single-bit fields appear only
/// when set; wider fields always, since 0 is meaningful there.
pub fn decode(register: &Register, value: u16) -> Vec<Decoded> {
    fields(register)
        .iter()
        .map(|&field| Decoded {
            field,
            value: field.extract(value),
        })
        .filter(|d| d.field.hi != d.field.lo || d.value != 0)
        .collect()
}

/// A one-line summary of a value, e.g. `SET DMAEN|BPLEN|COPEN` or
/// `HIRES BPU=4 COLOR`.
pub fn summarize(register: &Register, value: u16) -> String {
    if register.name.starts_with("COLOR") {
        let (r, g, b) = ((value >> 8) & 15, (value >> 4) & 15, value & 15);
        return format!("R={r} G={g} B={b}");
    }
    let parts: Vec<String> = decode(register, value)
        .into_iter()
        .filter(|d| !(register.is_set_clear() && d.field.name == "SETCLR"))
        .map(|d| {
            if d.field.hi == d.field.lo {
                d.field.name.to_string()
            } else {
                format!("{}={}", d.field.name, d.value)
            }
        })
        .collect();
    let body = if parts.is_empty() {
        "-".to_string()
    } else {
        parts.join("|")
    };
    if register.is_set_clear() {
        let verb = if value & 0x8000 != 0 { "SET" } else { "CLR" };
        format!("{verb} {body}")
    } else {
        body
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        assert!(REGISTERS.windows(2).all(|w| w[0].offset < w[1].offset));
        assert!(
            REGISTERS
                .iter()
                .all(|r| r.offset % 2 == 0 && r.offset < 0x200)
        );
    }

    #[test]
    fn lookups() {
        let dmacon = by_name("dmacon").unwrap();
        assert_eq!((dmacon.offset, dmacon.access), (0x096, Access::Write));
        assert_eq!(by_address(0xDFF180).unwrap().name, "COLOR00");
        assert_eq!(by_offset(0x10E).unwrap().name, "CLXCON2");
        assert_eq!(by_name("FMODE").unwrap().since, ChipSet::Aga);
        assert_eq!(by_name("BLTCON0").unwrap().copper, Copper::Danger);
        assert_eq!(by_name("DMACONR").unwrap().copper, Copper::No);
        assert!(by_address(0xDFF200).is_none());
    }

    #[test]
    fn summaries() {
        let r = |n| by_name(n).unwrap();
        assert_eq!(summarize(r("DMACON"), 0x8380), "SET DMAEN|BPLEN|COPEN");
        assert_eq!(
            summarize(r("INTENA"), 0x7FFF),
            "CLR INTEN|EXTER|DSKSYN|RBF|AUD3|AUD2|AUD1|AUD0|BLIT|VERTB|COPER|PORTS|SOFT|DSKBLK|TBE"
        );
        assert_eq!(summarize(r("BPLCON0"), 0x4200), "BPU=4|COLOR");
        assert_eq!(summarize(r("BLTSIZE"), (64 << 6) | 20), "H=64|W=20");
        assert_eq!(summarize(r("COLOR17"), 0x0F80), "R=15 G=8 B=0");
        assert_eq!(summarize(r("BLTCON0"), 0x09F0), "ASH=0|USEA|USED|LF=240");
        assert!(fields(r("BPL1PTH")).is_empty());
        assert!(!fields(r("SPR7CTL")).is_empty());
    }
}
