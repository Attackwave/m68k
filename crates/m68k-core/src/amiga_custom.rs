//! Amiga custom chip registers ($DFF000-$DFF1FE): names, access,
//! chipset generation, copper access and bit fields.
//!
//! The register set follows the hardware reference register summary for
//! OCS/ECS, extended by the ECS UHRES and AGA registers.

/// How the CPU may access a register.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Access {
    Read,
    Write,
    /// Writing triggers an action; the value is ignored.
    Strobe,
    /// DMA-only register read early in the bus cycle.
    EarlyRead,
}

/// The chipset that introduced the register or changed its meaning.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum ChipSet {
    Ocs,
    Ecs,
    Aga,
}

/// Whether the copper may write the register.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Copper {
    Yes,
    /// Only with the danger bit (COPCON bit 1) set.
    Danger,
    No,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Register {
    pub name: &'static str,
    /// Offset from $DFF000.
    pub offset: u16,
    pub access: Access,
    /// Agnus (A), Denise/Lisa (D), Paula (P).
    pub chips: &'static str,
    pub since: ChipSet,
    pub copper: Copper,
    pub description: &'static str,
}

impl Register {
    pub fn address(&self) -> u32 {
        CUSTOM_BASE + self.offset as u32
    }

    /// Registers with a SET/CLR bit 15: writing 1 sets the other written
    /// 1-bits, writing 0 clears them.
    pub fn is_set_clear(&self) -> bool {
        matches!(self.name, "DMACON" | "INTENA" | "INTREQ" | "ADKCON")
    }
}

/// A bit field of a register, bits `hi..=lo`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Field {
    pub hi: u8,
    pub lo: u8,
    pub name: &'static str,
    pub description: &'static str,
}

impl Field {
    pub fn extract(&self, value: u16) -> u16 {
        let width = self.hi - self.lo + 1;
        (value >> self.lo) & (((1u32 << width) - 1) as u16)
    }
}

pub const CUSTOM_BASE: u32 = 0xDFF000;

const fn reg(
    name: &'static str,
    offset: u16,
    access: Access,
    chips: &'static str,
    since: ChipSet,
    copper: Copper,
    description: &'static str,
) -> Register {
    Register {
        name,
        offset,
        access,
        chips,
        since,
        copper,
        description,
    }
}

