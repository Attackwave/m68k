/// Register by name, case-insensitively (`dmacon`, `COLOR00`).
pub fn by_name(name: &str) -> Option<&'static Register> {
    REGISTERS.iter().find(|r| r.name.eq_ignore_ascii_case(name))
}

/// Register at `offset` from $DFF000.
pub fn by_offset(offset: u16) -> Option<&'static Register> {
    REGISTERS
        .binary_search_by_key(&offset, |r| r.offset)
        .ok()
        .map(|i| &REGISTERS[i])
}

/// Register at an absolute address ($DFF000-$DFF1FE).
pub fn by_address(address: u32) -> Option<&'static Register> {
    let offset = address.checked_sub(CUSTOM_BASE)?;
    if offset >= 0x200 {
        return None;
    }
    by_offset(offset as u16)
}

